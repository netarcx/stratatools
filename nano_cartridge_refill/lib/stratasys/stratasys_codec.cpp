/*
 * Stratasys cartridge codec -- see stratasys_codec.h.
 *
 * EEPROM layout (offsets), from manager.py:
 *   0x00 serial number (binary64, encrypted as part of 0x00-0x40)
 *   0x08 material id (binary64)
 *   0x10 manufacturing lot (20s)
 *   0x24 version (uint16)
 *   0x28 manufacturing date / 0x30 use date
 *   0x38 initial material quantity (binary64)
 *   0x40 plaintext content CRC16
 *   0x46 encrypted content CRC16
 *   0x48 key (8 bytes, cleartext) / 0x50 key CRC16
 *   0x58 current material quantity (binary64, separately encrypted)
 *   0x60 encrypted current-qty CRC16 / 0x62 plaintext current-qty CRC16
 *   0x68 signature (9 bytes)
 */
